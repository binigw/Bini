type TranslationKey = keyof typeof translations.en;

type I18nValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey | string, fallback?: string) => string;
  localize: (value: { en: string; am: string } | string) => string;
  fault: (value: string | null | undefined) => string;
  alertMessage: (faultType: string, message: string) => string;
  relativeTime: (date: Date) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    return window.localStorage.getItem("voltguard-language") === "am" ? "am" : "en";
  });

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("voltguard-language", next);
  };

  const value = useMemo<I18nValue>(() => {
    const localizeFault = (value: string | null | undefined) => {
      if (!value) return translations[language]["dashboard.unavailable"];
      const map: Record<string, string> = {
        "Bearing Wear": language === "am" ? "የBearing መልበስ" : "Bearing Wear",
        "High THD": language === "am" ? "ከፍተኛ THD" : "High THD",
        "High Vibration": language === "am" ? "ከፍተኛ Vibration" : "High Vibration",
        "Phase Imbalance": language === "am" ? "የPhase አለመመጣጠን" : "Phase Imbalance",
        "Overcurrent": language === "am" ? "ከመጠን በላይ Current" : "Overcurrent",
        "INSTANTANEOUS_SHORT_CIRCUIT_TRIP": language === "am" ? "ፈጣን የShort Circuit መቋረጥ" : "Instantaneous Short-Circuit Trip",
        "OVERLOAD_TRIP": language === "am" ? "የOverload መቋረጥ" : "Overload Trip",
         "Normal": translations[language]["dashboard.normal"],
         "Low": translations[language]["dashboard.low"],
         "Medium": translations[language]["severity.medium"],
         "High": translations[language]["severity.high"],
         "Low Risk": language === "am" ? "ዝቅተኛ አደጋ" : "Low Risk",
         "Medium Risk": language === "am" ? "መካከለኛ አደጋ" : "Medium Risk",
         "High Risk": language === "am" ? "ከፍተኛ አደጋ" : "High Risk",
      };
      return map[value] ?? value;
    };

    return {
      language,
      setLanguage,
      t: (key: TranslationKey | string, fallback?: string) =>
        translations[language][key as TranslationKey] ?? translations.en[key as TranslationKey] ?? fallback ?? key,
      localize: (value: { en: string; am: string } | string) =>
        typeof value === "string" ? value : value[language] ?? value.en,
      fault: localizeFault,
      alertMessage: (faultType: string, message: string) => {
      if (language === "en") return message;
      return message.toLowerCase().includes("emergency trip")
        ? `${localizeFault(faultType)} — ${translations.am["dashboard.emergencyTripDetected"]}.`
        : `${localizeFault(faultType)} — ${translations.am["dashboard.alertDetected"]}.`;
      },
      relativeTime: (date: Date) => {
      const value = formatDistanceToNow(date);
      if (language === "en") return value;
      const match = value.match(/about (\d+) hours?/i) ?? value.match(/(\d+) hours?/i);
      if (match) return `ከ${match[1]} ሰዓት በፊት`;
      const minuteMatch = value.match(/(\d+) minutes?/i);
      if (minuteMatch) return `ከ${minuteMatch[1]} ደቂቃ በፊት`;
      if (/less than a minute/i.test(value)) return "ከአንድ ደቂቃ በታች በፊት";
      return `ከ${value} በፊት`;
      },
    };
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language === "am" ? "am" : "en";
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within LanguageProvider");
  return context;
}
